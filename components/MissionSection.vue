<script setup lang="ts">
import { ref, reactive } from 'vue'

const formData = reactive({
  name: '',
  phone: '',
  email: '',
  address: '',
  message: ''
})

const isSubmitting = ref(false)
const formStatus = ref<'idle' | 'success' | 'error'>('idle')
const errorMessage = ref('')

const handleSubmit = async () => {
  isSubmitting.value = true
  formStatus.value = 'idle'
  errorMessage.value = ''

  try {
    // Send email via Netlify Function
    const response = await fetch('/.netlify/functions/send-email', {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json'
      },
      body: JSON.stringify({
        name: formData.name,
        email: formData.email,
        phone: formData.phone,
        address: formData.address,
        message: formData.message
      })
    })

    const data = await response.json()

    if (!response.ok) {
      console.error('Server error:', data)
      throw new Error(data.error || data.details || 'Failed to send email')
    }

    formStatus.value = 'success'
    
    // Reset form after 3 seconds
    setTimeout(() => {
      Object.keys(formData).forEach(key => {
        formData[key as keyof typeof formData] = ''
      })
      formStatus.value = 'idle'
    }, 3000)

  } catch (error) {
    console.error('Error sending email:', error)
    formStatus.value = 'error'
    
    // Show detailed error message
    if (error instanceof Error) {
      errorMessage.value = error.message.includes('fetch')
        ? 'Unable to connect to email service. Please call us directly at +91 99739 53809'
        : error.message
    } else {
      errorMessage.value = 'Failed to send message. Please call us directly at +91 99739 53809'
    }
  } finally {
    isSubmitting.value = false
  }
}
</script>
